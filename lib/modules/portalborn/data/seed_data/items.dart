List<GameItem> get materials => itemTemplates.where((i) => i.isMaterial).toList();

/// 根据物品ID获取模板
GameItem? getItemTemplate(String id) {
  try {
    return itemTemplates.firstWhere((i) => i.id == id);
  } catch (_) {
    return null;
  }
}

/// 根据标签获取物品列表
List<GameItem> getItemsByTag(String tag) {
  return itemTemplates.where((i) => i.tags.contains(tag)).toList();
}

/// 根据类型获取物品列表
List<GameItem> getItemsByType(String type) {
  return itemTemplates.where((i) => i.type == type).toList();
}